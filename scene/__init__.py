import os
import random
import json
import hashlib
import numpy as np
from utils.system_utils import searchForMaxIteration
from scene.dataset_readers import sceneLoadTypeCallbacks
from scene.gaussian_model import GaussianModel
from arguments import ModelParams
from utils.camera_utils import cameraList_from_camInfos, camera_to_JSON

class Scene:

    gaussians : GaussianModel

    @staticmethod
    def _conf_camera_identity(cam_info, source_path):
        """Describe an image/view independently of scene loading order."""
        return json.dumps({
            'path': os.path.relpath(cam_info.image_path, source_path),
            'R': np.asarray(cam_info.R, dtype=np.float64).tolist(),
            'T': np.asarray(cam_info.T, dtype=np.float64).tolist(),
            'fov': [float(cam_info.FovX), float(cam_info.FovY)],
            'size': [int(cam_info.width), int(cam_info.height)],
        }, sort_keys=True, separators=(',', ':'))

    def __init__(self, args : ModelParams, gaussians : GaussianModel, load_iteration=None, shuffle=True, resolution_scales=[1.0]):
        """b
        :param path: Path to colmap scene main folder.
        """
        self.model_path = args.model_path
        self.loaded_iter = None
        self.gaussians = gaussians

        if load_iteration:
            if load_iteration == -1:
                self.loaded_iter = searchForMaxIteration(os.path.join(self.model_path, "point_cloud"))
            else:
                self.loaded_iter = load_iteration
            print("Loading trained model at iteration {}".format(self.loaded_iter))

        self.train_cameras = {}
        self.test_cameras = {}

        if os.path.exists(os.path.join(args.source_path, "sparse")):
            scene_info = sceneLoadTypeCallbacks["Colmap"](args.source_path, args.images, args.eval)
        elif os.path.exists(os.path.join(args.source_path, "transforms_train.json")):
            print("Found transforms_train.json file, assuming Blender data set!")
            scene_info = sceneLoadTypeCallbacks["Blender"](args.source_path, args.white_background, args.eval)
        else:
            assert False, "Could not recognize scene type!"

        # A camera's enumeration UID changes when the scene is shuffled, and
        # COLMAP intrinsic-camera IDs may be shared by many images. Use a
        # deterministic image/pose identity, checking both duplicate images
        # and the (extremely unlikely) truncated-hash collision explicitly.
        conf_keys = {}
        conf_mapping = {}
        for cam_info in scene_info.train_cameras:
            identity = self._conf_camera_identity(cam_info, args.source_path)
            key = int.from_bytes(hashlib.sha256(identity.encode('utf-8')).digest()[:8], 'big') & ((1 << 63) - 1)
            if key in conf_mapping:
                raise ValueError('Duplicate or colliding Conf training-camera identity')
            conf_keys[identity] = key
            conf_mapping[key] = identity
        self.gaussians.set_conf_camera_mapping(conf_mapping)

        if not self.loaded_iter:
            with open(scene_info.ply_path, 'rb') as src_file, open(os.path.join(self.model_path, "input.ply") , 'wb') as dest_file:
                dest_file.write(src_file.read())
            json_cams = []
            camlist = []
            if scene_info.test_cameras:
                camlist.extend(scene_info.test_cameras)
            if scene_info.train_cameras:
                camlist.extend(scene_info.train_cameras)
            for id, cam in enumerate(camlist):
                json_cams.append(camera_to_JSON(id, cam))
            with open(os.path.join(self.model_path, "cameras.json"), 'w') as file:
                json.dump(json_cams, file)

        if shuffle:
            random.shuffle(scene_info.train_cameras)  # Multi-res consistent random shuffling
            random.shuffle(scene_info.test_cameras)  # Multi-res consistent random shuffling

        self.cameras_extent = scene_info.nerf_normalization["radius"]

        for resolution_scale in resolution_scales:
            print("Loading Training Cameras")
            self.train_cameras[resolution_scale] = cameraList_from_camInfos(scene_info.train_cameras, resolution_scale, args)
            for cam_info, camera in zip(scene_info.train_cameras, self.train_cameras[resolution_scale]):
                camera.conf_camera_key = conf_keys[self._conf_camera_identity(cam_info, args.source_path)]
            print("Loading Test Cameras")
            self.test_cameras[resolution_scale] = cameraList_from_camInfos(scene_info.test_cameras, resolution_scale, args)

        if self.loaded_iter:
            self.gaussians.load_ply(os.path.join(self.model_path,
                                                           "point_cloud",
                                                           "iteration_" + str(self.loaded_iter),
                                                           "point_cloud.ply"))
        else:
            self.gaussians.create_from_pcd(scene_info.point_cloud, self.cameras_extent)

    def save(self, iteration):
        point_cloud_path = os.path.join(self.model_path, "point_cloud/iteration_{}".format(iteration))
        self.gaussians.save_ply(os.path.join(point_cloud_path, "point_cloud.ply"))

    def getTrainCameras(self, scale=1.0):
        return self.train_cameras[scale]

    def getTestCameras(self, scale=1.0):
        return self.test_cameras[scale]
